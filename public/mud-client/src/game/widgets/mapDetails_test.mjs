import assert from 'node:assert/strict';
import {townFortifications,mountainDepth,reliefAt,forestSpecies} from './mapDetails.js';
import {undergroundModel} from './undergroundRenderer.js';
import {computeCamera,clampMapScale} from './atlasRenderer.js';
const town=[{id:'a',x:0,y:0},{id:'b',x:0,y:2},{id:'c',x:2,y:2},{id:'d',x:2,y:3}];
const outside={id:'outside',x:-3,y:0};
const roads=[{a:town[0],b:town[1]},{a:town[1],b:town[2]},{a:town[2],b:town[3]},{a:town[0],b:outside}];
const walls=townFortifications(town,roads);
assert.ok(walls.loops.some(l=>l.length>4),'bent streets produce concave angular walls');
assert.ok(walls.towers.length>=4,'courtyard corners receive towers');
assert.equal(walls.gates.length,1);assert.ok(walls.gates[0].x<0&&walls.gates[0].y===0,'gate lies on the incoming road');
const cells=[];for(let y=0;y<11;y++)for(let x=0;x<11;x++)cells.push({x,y,terrain:'mountain'});
const depth=mountainDepth(cells,new Map(cells.map(c=>[`${c.x}:${c.y}`,c])));
assert.equal(depth.get('0:0'),0);assert.equal(depth.get('5:5'),5);
assert.equal(reliefAt(cells[0],depth).kind,'hill');assert.ok(reliefAt({x:5,y:5},depth).variant>=4);
assert.equal(forestSpecies('Thornfield Highlands','forest'),'pine');assert.equal(forestSpecies('Ashenvale Woods','forest'),'oak');assert.equal(forestSpecies('Gloomfen Marsh','swamp'),'deadTree');
const places=[{id:'a',x:0,y:0,layer:'lower',area:'cave',discovered:true},{id:'b',x:1,y:0,layer:'lower',area:'cave',discovered:true},{id:'remote',x:4,y:7,layer:'lower',area:'cave',discovered:true}];
const model=undergroundModel({places,paths:[{from:'a',to:'b',dir:'east'},{from:'a',to:'remote',dir:'southwest'}]});
assert.equal(model.corridors.length,1,'normal short compass tunnels stay; void-crossing diagonals are omitted');
const frame=[{x:-22,y:-32},{x:24,y:31}];
const fit=computeCamera(frame,1205,819,0,0,1),far=computeCamera(frame,1205,819,0,0,.01);
assert.equal(clampMapScale(.01),1);assert.equal(far.tileStep,fit.tileStep,'minimum zoom and world fit share framing');
assert.ok(fit.tileStep*60/819>.7&&fit.tileStep*60/819<.8,'continent occupies 70-80 percent of map height');
console.log('mapDetails: angular town footprints/gates, mountain edge relief, biome species, void links and minimum zoom OK');
