import assert from 'node:assert/strict';
import { tileKeyFor, terrainConnectors, computeCamera, clampMapScale } from './atlasRenderer.js';
assert.equal(tileKeyFor({discovered:false,terrain:'castle'}),'fog');
assert.equal(tileKeyFor({discovered:true,kind:'uncharted',terrain:'forest'}),'fog');
assert.equal(tileKeyFor({discovered:true,terrain:'forest'}),'forest');
assert.equal(tileKeyFor({discovered:true,terrain:'invalid'}),'grassland');
assert.equal(tileKeyFor({discovered:true,terrain:'sea'}),'grassland');
const a={id:'A',x:0,y:0,area:'vale',layer:'overworld',discovered:true,terrain:'farmland'};
const b={...a,id:'B',x:3,terrain:'grassland'};
const paths=[{from:'A',to:'B',dir:'east',kind:'trail'},{from:'B',to:'A',dir:'west',kind:'trail'}];
const fills=terrainConnectors([a,b],paths);
assert.deepEqual(fills.map(p=>[p.x,p.y,p.terrain]),[[1,0,'farmland'],[2,0,'farmland']]);
for(const change of [{discovered:false},{area:'town'},{layer:'upper'}])assert.equal(terrainConnectors([a,{...b,...change}],paths).length,0);
assert.equal(terrainConnectors([a,b,{...a,id:'fog',x:1,discovered:false}],paths).length,1,'occupied fog cell cannot become ground');
assert.equal(terrainConnectors([a,b],[{...paths[0],kind:'hidden'}]).length,0);
assert.equal(terrainConnectors([a,{...b,x:20}],paths).length,0,'long exits do not fill entire sea');
const world=[a,{...b,x:80,y:50}];
const zoom=computeCamera(world,800,600,0,0,.5);
assert.ok(zoom.tileStep<28,'overview can fit multiple distant zones');
assert.equal(clampMapScale(.01),.12);
console.log('terrainRenderer: fog, terrain keys, zone/layer connectors, overview zoom OK');
