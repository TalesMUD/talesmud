import assert from 'node:assert/strict';
import { get } from 'svelte/store';
import { createStore, normalizeCombatant } from './MUDXPlusStore.js';
import { phaseBanner, phaseCaption } from './bossPhases.js';
const boss = { id:'boss', name:'Warden', type:'npc', hp:100, maxHp:100, bossPhase:1, bossPhaseLabel:'Opening', bossPhaseCount:3 };
const store = createStore();
store.beginCombat([boss], [{id:'hero',type:'player',hp:80,maxHp:80}], 'Fight');
assert.equal(phaseCaption(get(store).combatEnemies[0]), 'Phase 1 / 3 · Opening');
assert.equal(get(store).combatPhaseEnter, null);
store.applyCombatAction({ action:'phase-enter', result:'phase-enter', actorId:'boss', message:'Warden enters phase 2: Escalation!', combatants:[{...boss,hp:66,bossPhase:2,bossPhaseLabel:'Escalation'}] });
const notice = get(store).combatPhaseEnter;
assert.equal(phaseBanner(notice,notice.at+3999,true), 'Warden enters phase 2: Escalation!');
assert.equal(phaseBanner(notice,notice.at+4000,true), '');
assert.equal(phaseBanner(notice,notice.at,false), '');
assert.equal(phaseCaption(get(store).combatEnemies[0]), 'Phase 2 / 3 · Escalation');
store.applyCombatAction({action:'attack',result:'hit',targetId:'hero',damage:3});
assert.deepEqual(get(store).combatPhaseEnter,notice,'later attacks must not erase the phase beat');
assert.equal(phaseCaption(normalizeCombatant({id:'rat',hp:10,maxHp:10})), '');
store.beginCombat([{...boss,bossPhase:3,bossPhaseLabel:'Last Stand'}], [], 'Joined');
assert.equal(get(store).combatPhaseEnter,null,'joining or starting a later fight must not replay a transition');
assert.equal(phaseCaption(get(store).combatEnemies[0]),'Phase 3 / 3 · Last Stand');
console.log('bossPhases_test ok');
